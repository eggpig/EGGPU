POLICY_SOURCE = Path(__file__).resolve().parent.parent / 'egmgpu' / 'sssp_policy.py'
# Full edge/weight content hash, independent of partition layout, generated by
# load_weighted_manifest_graph; source file checksums are also checked every load.
QUALIFIED_WEIGHTED_SHA256 = '9d01a545fcfb58be2502805c28f3b26ff427a215084fcf68b3c8d2e55514f5c6'


# Per-process observability only. The same two integer increments are performed
# for each successful-domain call in both arms; they remain inside query timing.
_WCC_CANONICAL_CERTIFICATE_AUDIT = {'calls': 0, 'off': 0, 'certified': 0, 'fallback': 0}


# A fixed working-set bound, independent of graph identity or measured timings.
_WCC_CANONICAL_CHUNK = 1 << 15


def canonical_wcc(labels, count, *, certify_minimum=None, _arena_scope=None, _arena_graph=None, _arena_cpu_certificate=False):
    """Return an owned float64 minimum dense index for every component.

    Validate every label even after a certificate fails. Only the final public
    output (and the dense root table on fallback) scales with the whole graph;
    validation, indexing and certificate scratch are bounded by a fixed chunk.
    """
    array = np.asarray(labels)
    if array.shape != (count,) or array.dtype.kind not in 'iuf':
        raise ValueError('WCC requires one numeric dense-index component label per node')
    mode = (os.environ.get('EGGPU_WCC_CANONICAL_CERTIFICATE', '0')
            if certify_minimum is None else '1' if certify_minimum else '0')
    if (mode == '1' and _arena_scope is not None
            and _consume_canonical_wcc_download(_arena_scope, _arena_graph, array)):
        # Only the completed internal monotone-union producer can mint this
        # one-use capability. Generic arrays and native results keep the full
        # domain/canonicalization checks and noncanonical-label fallback below.
        _WCC_CANONICAL_CERTIFICATE_AUDIT['calls'] += 1
        _WCC_CANONICAL_CERTIFICATE_AUDIT['certified'] += 1
        return array
    certified = mode == '1'
    floating = array.dtype.kind == 'f'
    cpu_certificate = None
    if (_arena_cpu_certificate is True and _arena_scope is not None and mode == '1'
            and array.dtype == np.dtype(np.float64) and array.flags.c_contiguous
            and array.flags.aligned):
        # A pure-Python installation or an older extension can use the same
        # complete value checks below; neither can mint a producer capability.
        try:
            import cpp_easygraph
        except ImportError:
            pass
        else:
            cpu_certificate = getattr(cpp_easygraph, 'cpp_egmgpu_certify_wcc_float64', None)
    if callable(cpu_certificate):
        complete_certificate = cpu_certificate(array, count)
        certified = certified and complete_certificate
    else:
        for first in range(0, count, _WCC_CANONICAL_CHUNK):
            last = min(count, first + _WCC_CANONICAL_CHUNK)
            block = array[first:last]
            # Integers are already finite and integral; floats require both checks.
            if ((floating and not np.all(np.isfinite(block)))
                    or np.any(block < 0) or np.any(block >= count)
                    or (floating and np.any(block != np.floor(block)))):
                raise ValueError('WCC component labels must be exact dense indices')
            if certified:
                indices = block.astype(np.intp, copy=False)
                # The representative belongs to this same group and precedes every
                # member. Together these prove that it is exactly the group's min.
                certified = (np.all(array[indices] == block)
                             and np.all(block <= np.arange(first, last, dtype=np.int64)))
    if mode not in ('0', '1'):
        raise ValueError('EGGPU_WCC_CANONICAL_CERTIFICATE must be 0 or 1')
    _WCC_CANONICAL_CERTIFICATE_AUDIT['calls'] += 1
    if mode == '1':
        if certified:
            _WCC_CANONICAL_CERTIFICATE_AUDIT['certified'] += 1
            # The complete label-domain and minimum-root certificate above is
            # necessary but not sufficient for adoption. Only this request's
            # actual fresh download can transfer its allocation once. General
            # callers, aliases and transformed/backend-held arrays still copy.
            if _arena_scope is not None and _consume_download(_arena_scope, _arena_graph, 'wcc', array):
                return array
            return array.astype(np.float64, copy=True)
        _WCC_CANONICAL_CERTIFICATE_AUDIT['fallback'] += 1
    else:
        _WCC_CANONICAL_CERTIFICATE_AUDIT['off'] += 1
    # All labels were proven to be dense indices. Index the root table by the
    # original label directly; grouping/sorting the entire vector is unnecessary.
    roots = np.full(count, count, dtype=np.int64)
    for first in range(0, count, _WCC_CANONICAL_CHUNK):
        last = min(count, first + _WCC_CANONICAL_CHUNK)
        indices = array[first:last].astype(np.intp, copy=False)
        np.minimum.at(roots, indices, np.arange(first, last, dtype=np.int64))
    output = np.empty(count, dtype=np.float64)
    for first in range(0, count, _WCC_CANONICAL_CHUNK):
        last = min(count, first + _WCC_CANONICAL_CHUNK)
        output[first:last] = roots[array[first:last].astype(np.intp, copy=False)]
    return output


def wcc_contract():
    return QueryContract('wcc', None, 'unweighted weak connectivity', None, None, None, None, None,
                         output_order='values[i] is the minimum dense index of its component; original representative is node_ids[int(values[i])]')


def sssp_certificate(weights, vertex_count, encoding):
    if isinstance(vertex_count, (bool, np.bool_)):
        raise ValueError('Vertex count must be a positive integer')
    n = operator.index(vertex_count)
    if n <= 0 or encoding not in ('f64', 'u8_exact_u32_exact'):
        raise ValueError('Invalid SSSP numeric contract')
    array = np.asarray(weights)
    if array.ndim != 1 or array.dtype.kind != 'f' or array.dtype.itemsize != 8:
        raise ValueError('SSSP certificate requires original float64 weights; no silent input casts')
    if not np.all(np.isfinite(array)) or np.any(array < 0):
        raise ValueError('SSSP requires finite nonnegative weights')
    maximum = float(array.max(initial=0))
    bound = (n - 1) * maximum
    if not np.isfinite(bound):
        raise ValueError('SSSP finite path bound overflows float64')
    if encoding == 'u8_exact_u32_exact':
        if np.any(array != np.floor(array)) or maximum > 255:
            raise ValueError('u8_exact requires exact integer float64 weights in [0,255]')
        if bound >= 2**32 - 1:
            raise ValueError('Finite distance bound collides with u32 unreachable sentinel')
    return {'encoding':encoding, 'vertex_count':n, 'weights_count':len(array), 'max_weight':maximum,
            'finite_distance_upper_bound':bound, 'weights_f64_sha256':hashlib.sha256(array.astype('<f8').tobytes()).hexdigest(),
            'proof':'Nonnegative shortest path can be simple: at most n-1 edges; u32 UINT_MAX reserved for unreachable',
            'f64_note':'No weight compression; float64 arithmetic, not arbitrary precision'}


def load_weighted_manifest_graph(path):
    path = Path(path).resolve()
    document = json.loads(path.read_text())
    graph, view = document['graph'], document['view']
    n = int(graph['vertex_count'])
    if (not graph['weighted'] or view['orientation'] not in ('outgoing','undirected')
            or not 0 < n <= 100000 or not 0 <= graph['adjacency_count'] <= 2000000):
        raise ValueError('Expected small weighted outgoing/undirected qualification graph')
    dtype_map = {'int32':'<i4','uint64':'<u8','float64':'<f8'}
    hashes, blocks, weights, owned_blocks = {}, [], [], []
    for partition in document['partitions']:
        arrays = {}
        for name, spec in partition['files'].items():
            target = (path.parent/spec['path']).resolve()
            target.relative_to(path.parent)
            payload = target.read_bytes()
            digest = hashlib.sha256(payload).hexdigest()
            if len(payload) != spec['byte_size'] or digest != spec['sha256']:
                raise ValueError('Weighted manifest payload checksum/size mismatch')
            array = np.frombuffer(payload, dtype=dtype_map[spec['dtype']])
            if len(array) != spec['count']:
                raise ValueError('Weighted manifest cardinality mismatch')
            hashes[str(target)], arrays[name] = digest, array
        rows, cols, ids, owned = (arrays[k] for k in ('offsets','indices','local_to_global','owned_global_ids'))
        weight = arrays['weights']
        if (len(owned) != partition['owned_vertex_count'] or len(rows) != len(owned)+1
                or rows[0] != 0 or rows[-1] != len(cols) or np.any(np.diff(rows)<0)
                or len(weight) != len(cols) or weight.dtype != np.dtype('<f8')):
            raise ValueError('Weighted CSR shape/order mismatch')
        if np.any(ids >= n) or (len(cols) and (cols.min()<0 or cols.max()>=len(ids))):
            raise ValueError('Weighted CSR vertex outside domain')
        np.testing.assert_array_equal(ids[:len(owned)],owned)
        owned_blocks.append(owned)
        blocks.append(np.column_stack((np.repeat(owned,np.diff(rows)),ids[cols])))
        weights.append(weight)
    np.testing.assert_array_equal(np.sort(np.concatenate(owned_blocks)),np.arange(n,dtype=np.uint64))
    edges, values = np.concatenate(blocks).astype(np.int64), np.concatenate(weights)
    order = np.lexsort((edges[:,1],edges[:,0]))
    edges, values = edges[order], values[order]
    if len(edges) != graph['adjacency_count'] or np.any(np.all(edges[1:]==edges[:-1],axis=1)):
        raise ValueError('Weighted adjacency count/duplicate mismatch')
    certificate = sssp_certificate(values,n,'f64')
    digest = hashlib.sha256(json.dumps({'vertex_count':n,'directed':graph['directed'],'weighted':True},sort_keys=True).encode())
    digest.update(edges.astype('<i8').tobytes())
    digest.update(values.astype('<f8').tobytes())
    return {'nodes':np.arange(n,dtype=np.int64),'edges':edges,'weights':values}, {
        'manifest':str(path),'manifest_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
        'payload_sha256':hashes,'canonical_graph_sha256':digest.hexdigest(),
        'partition_count':len(document['partitions']),'vertex_count':n,'adjacency_count':len(edges),
        'weight_certificate':certificate,'identity_verified_by':'complete owned CSR rows and float64 weights, every declared payload checksum'}


def load_weighted_family(directory, counts=(1,2,4)):
    canonical, receipts = None, {}
    for count in counts:
        data, receipt = load_weighted_manifest_graph(Path(directory)/f'weighted-{count}gpu/manifest.json')
        if receipt['partition_count'] != count:
            raise ValueError('Wrong weighted partition count')
        if canonical is not None:
            for key in data:
                np.testing.assert_array_equal(canonical[key],data[key])
        else:
            canonical = data
        receipts[str(count)] = receipt
    if canonical is None:
        raise ValueError('At least one weighted layout required')
    return canonical, receipts


def native_policy(encoding):
    # Reuse the final read-only policy implementation, including its strict
    # observation checker. Importing this pure-Python file does not load CUDA.
    name = '_eggpu_core_frozen_sssp_policy'
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name,POLICY_SOURCE)
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        try:
            spec.loader.exec_module(module)
        except BaseException:
            sys.modules.pop(name, None)
            raise
    module = sys.modules[name]
    if encoding not in ('f64','u8_exact_u32_exact'):
        raise ValueError('Unknown native SSSP encoding')
    compact = encoding != 'f64'
    local = os.environ.get('EGGPU_SINGLE_OWNER_SSSP', '0')
    if local not in ('0','1'): raise ValueError('EGGPU_SINGLE_OWNER_SSSP must be 0 or 1')
    policy = module.SsspExecutionPolicy(single_owner_execution='arena_v3_if_eligible' if local=='1' else 'off', delta=16., weight_encoding='u8_exact' if compact else 'f64',
        wire_encoding='u32_exact' if compact else 'f64', output_team='worker1', atomic_min='native_u64',
        exchange_sync='trim',pinned_placement='numa_local',host_assembly='worker',relax_policy='warp',
        control_policy='warp',weight_identity='manifest_f64',profile=False,pinned_reuse=True,
        prepared_uploads=True,allow_undirected=True)
    return policy, module.verify_policy_observation


class CoreManagedSession(ManagedSession):
    capabilities = ManagedSession.capabilities | {'wcc'}

    def _query(self, graph_id, algorithm, parameters=None, begin=None):
        if algorithm != 'wcc':
            return super()._query(graph_id,algorithm,parameters,begin)
        begin = perf_counter() if begin is None else begin
        if self.closed:
            raise RuntimeError('Session closed')
        if parameters:
            raise ValueError('WCC takes no parameters')
        with _download_request(graph_id, 'wcc') as scope:
            downloaded = self.backend.query(graph_id,'wcc',{})
            canonical_begin = perf_counter()
            values = canonical_wcc(downloaded,len(self.nodes[graph_id]),certify_minimum=True,
                                   _arena_scope=scope,_arena_graph=graph_id,
                                   _arena_cpu_certificate=True)
            canonical_seconds = perf_counter() - canonical_begin
            adopted = values is downloaded
            metrics = copy.deepcopy(self.backend.last)
            metrics['wcc_public_output'] = dict(canonicalization='minimum_root_producer_or_cpu_certificate',
                bridge_copy_bytes=0, bridge_copy_bytes_avoided=int(values.nbytes),
                canonicalization_seconds=canonical_seconds,
                canonical_output_write_bytes=0 if adopted else int(values.nbytes),
                canonical_copy_bytes_avoided=int(values.nbytes) if adopted else 0,
                ownership='adopt_certified_arena_download' if adopted else 'adopt_private_canonical_array')
            # Either the strict producer capability was consumed after the full
            # certificate, or canonical_wcc allocated this independent result.
            return self._own_result(graph_id,'wcc',values,begin,metrics,{},contract=wcc_contract(),
                                    _private_owned=_ARENA_WCC_OWNED_OUTPUT)

    def _own_result(self, graph_id, algorithm, values, begin, metrics, parameters, *, contract=None, _private_owned=None, _arena_scope=None):
        if algorithm == 'sssp':
            contract = replace(query_contract(algorithm,parameters,len(self.nodes[graph_id])),weight_projection='input edge weights')
        return super()._own_result(graph_id,algorithm,values,begin,metrics,parameters,contract=contract,
                                   _private_owned=_private_owned, _arena_scope=_arena_scope)

    def capability_descriptor(self):
        descriptor = super().capability_descriptor()
        return replace(descriptor,algorithms=descriptor.algorithms+('wcc',),
                       qualification='WCC canonical dense-index labels; integration qualification recorded per cohort')


class CoreNativeSession(NativePartitionSession):
    capabilities = NativePartitionSession.capabilities | {'wcc','sssp'}

    def __init__(self, cpp, manifests, *, devices=(0,), sssp_encoding='f64'):
        self.sssp_encoding = sssp_encoding
        self.sssp_policy, self._verify_sssp_policy = native_policy(sssp_encoding)
        self.weighted_receipts = {}
        super().__init__(cpp,manifests,devices=devices)

    def _validate_manifest_document(self, name, path, document):
        if not document['graph'].get('weighted',False):
            return super()._validate_manifest_document(name,path,document)
        data, receipt = load_weighted_manifest_graph(path)
        if receipt['canonical_graph_sha256'] != QUALIFIED_WEIGHTED_SHA256:
            raise ValueError('Native weighted integration currently admits only the verified tiny qualification content')
        receipt['weight_certificate'] = sssp_certificate(data['weights'],len(data['nodes']),self.sssp_encoding)
        self.weighted_receipts[name] = receipt

    def _query(self, graph_id, algorithm, parameters=None, begin=None):
        begin = perf_counter() if begin is None else begin
        if self.closed:
            raise RuntimeError('Session closed')
        weighted = self.metadata[graph_id].get('weighted',False)
        if weighted and algorithm != 'sssp':
            raise NotImplementedError('Weighted native manifest is admitted only for explicit SSSP; weighted PR/BFS/WCC are not silently inferred')
        if algorithm not in ('sssp','wcc'):
            return super()._query(graph_id,algorithm,parameters,begin)
        parameters = dict(parameters or {})
        n, graph = len(self.nodes[graph_id]), self.graphs[graph_id]
        if algorithm == 'wcc':
            document = self._manifest_documents[graph_id]
            if document['graph'].get('directed',False) or document.get('view',{}).get('orientation') != 'undirected':
                raise NotImplementedError('Frozen native WCC requires an undirected CSR manifest')
            if parameters:
                raise ValueError('WCC takes no parameters')
            raw = self.cpp.cpp_egmgpu_partitioned_wcc(graph,100000,self.devices,dense_output=True)
            values = canonical_wcc(raw['labels_dense'],n)
            contract = wcc_contract()
        else:
            if not weighted or graph_id not in self.weighted_receipts:
                raise NotImplementedError('Native SSSP requires certified weighted qualification input')
            source = source_parameter(parameters)
            if not 0 <= source < n:
                raise ValueError('Source outside manifest node domain')
            parameters['source'] = source
            raw = self.cpp.cpp_egmgpu_partitioned_sssp(graph,source,self.sssp_policy.delta,0,self.devices,
                       dense_output=True,execution_policy=self.sssp_policy.native_options())
            self._verify_sssp_policy(raw,self.sssp_policy)
            values = np.asarray(raw['values_dense'])
            if (values.shape != (n,) or np.any(np.isnan(values)) or np.any(values < 0)
                    or values[source] != 0):
                raise RuntimeError('Native SSSP returned invalid complete distances')
            contract = replace(query_contract('sssp',parameters,n),weight_projection='input edge weights')
        if raw.get('converged') is not True or list(raw.get('devices_used',())) != self.devices:
            raise RuntimeError('Native algorithm did not converge on requested logical devices')
        metrics = {k:v for k,v in raw.items() if k not in ('values','values_dense','labels_dense')}
        if algorithm == 'sssp':
            metrics['input_certificate'] = self.weighted_receipts[graph_id]['weight_certificate']
        return self._own_result(graph_id,algorithm,values,begin,copy.deepcopy(metrics),parameters,contract=contract)

    def describe(self, graph_id):
        descriptor = super().describe(graph_id)
        if graph_id in self.weighted_receipts:
            descriptor = replace(descriptor,provenance={**descriptor.provenance,
                'verified_weighted_input':copy.deepcopy(self.weighted_receipts[graph_id])})
        return descriptor

    def capability_descriptor(self):
        descriptor = super().capability_descriptor()
        return replace(descriptor,algorithms=('bfs','pr','wcc','sssp'),
            qualification='BFS/PR unweighted; WCC undirected unweighted CSR; SSSP only certified tiny weighted input; explicit encoding policy verified per call',
            limitations=tuple(x for x in descriptor.limitations if not x.startswith('SSSP/TC/WCC')) +
            ('No arbitrary weighted-input integration qualification','Weighted PR explicitly rejected','No TC or remaining native functions exposed'))
