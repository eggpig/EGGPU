def readme_text(
    asset_dir_name: str,
    evidence_hashes: dict[str, str],
    rows: list[HeadlineRow],
    ledger_rows: int,
    manifest_counts: dict[str, int],
    estimator_policy: str,
    estimator_manifest_name: str,
) -> str:
    library, native, strict_nx = rows
    lines = [
        "# Headline-results table provenance",
        "",
        "This table was generated deterministically from the final audited asset",
        f"directory `{asset_dir_name}`. The cell ledger is the numerical source;",
        "the pairwise files and numeric summary are mandatory cross-checks.",
        "",
        "## Evidence",
        "",
        "| File | SHA-256 | Role |",
        "|---|---|---|",
    ]
    roles = {
        LEDGER_NAME: "authoritative cell-level status and timing values",
        PAIRWISE_NAME: "independent pairwise-best cross-check",
        BASELINE_PAIRWISE_NAME: "strict nx-cugraph per-function cross-check",
        NUMERIC_SUMMARY_NAME: "independent aggregate cross-check",
        estimator_manifest_name: (
            "five-run estimator, sample-SD, and ledger-hash gate"
        ),
    }
    for name in (
        LEDGER_NAME,
        PAIRWISE_NAME,
        BASELINE_PAIRWISE_NAME,
        NUMERIC_SUMMARY_NAME,
        estimator_manifest_name,
    ):
        lines.append(f"| `{name}` | `{evidence_hashes[name]}` | {roles[name]} |")
    lines.extend(
        [
            "",
            "## Denominator gates",
            "",
            f"- Complete matrix: {ledger_rows:,} rows = "
            f"{EXPECTED_DATASETS} datasets × {EXPECTED_FUNCTIONS} functions × "
            f"{len(EXPECTED_SYSTEMS)} systems.",
            f"- EGGPU: {EXPECTED_WORKLOADS}/{EXPECTED_WORKLOADS} validated workloads.",
            f"- Successful system--workload cells: "
            f"{manifest_counts['successful_cells']:,}.",
            f"- Displayed timing metrics: {manifest_counts['displayed_metrics']:,}; "
            f"portable raw observations: {manifest_counts['portable_raw_rows']:,}.",
            (
                "- Estimator: EGGPU uses `minimum_of_five`; external "
                "baselines use `arithmetic_mean_of_five`."
                if estimator_policy == MIXED_ESTIMATOR_POLICY
                else "- Estimator: `minimum_of_five` for every system."
            ),
            (
                "- Error: five-run sample standard deviation (`ddof=1`); "
                f"all {EXPECTED_SAMPLE_COUNT} correctness-qualified "
                "observations are retained."
            ),
            f"- Tie tolerance: {100 * RELATIVE_TIE_TOLERANCE:.2f}% relative.",
            "",
            "For every row, `W + T + L = common pairs` and",
            f"`common pairs + EGGPU-only = {EXPECTED_WORKLOADS}`.",
            "",
            "## Derived rows",
            "",
        ]
    )
    row_descriptions = (
        (
            library,
            "pairwise fastest correctness-qualified library baseline "
            "(NetworkX, EasyGraph CPU, EasyGraph C++, iGraph, GraphScope, or "
            "strict nx-cugraph)",
        ),
        (
            native,
            "pairwise fastest correctness-qualified native-GPU device interval "
            "(strict nx-cugraph or Gunrock)",
        ),
        (
            strict_nx,
            "strict nx-cugraph public-call E2E only",
        ),
    )
    for row, comparator in row_descriptions:
        lines.extend(
            [
                f"### {row.display_label}",
                "",
                f"- Comparator: {comparator}.",
                f"- Common pairs: {row.common_pairs}.",
                f"- EGGPU W/T/L: {row.eggpu_strict_wins}/"
                f"{row.eggpu_ties}/{row.eggpu_losses}.",
                f"- EGGPU-only versus this set: {row.eggpu_only_vs_set}.",
                f"- Geometric-mean speedup: "
                f"{format(row.geomean_speedup, '.17g')} "
                f"(displayed as {row.display_speedup}).",
                "",
            ]
        )
    lines.extend(
        [
            "EGGPU-only is comparison-set conditional and is excluded from W/T/L",
            "and geometric-mean speedup. Native-GPU processing never mixes GPU",
            "device timers with CPU wall-time surrogates.",
            "",
            "## Output contract",
            "",
            f"- `{OUTPUT_CSV}`: exact machine-readable values.",
            f"- `{OUTPUT_TEX}`: compact LaTeX table; no background fills.",
            f"- `{OUTPUT_MANIFEST}`: input/output hashes and machine-readable gates.",
            "- The generator does not edit or include the table in a paper source.",
            "",
        ]
    )
    return "\n".join(lines)


